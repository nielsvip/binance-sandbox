def off_value(name: str, current):
    """Off value for a member: TF-selectors -> 'OFF', bools -> False."""
    if isinstance(current, str):
        return "OFF"
    if isinstance(current, bool):
        return False
    return None


def apply(cfg) -> list:
    """Force every member of each True flag to its off value. Returns forced keys.

    Call AFTER overrides are applied (simulate_one top). All flags False =
    zero reads of member values, zero writes (behavior-preserving by construction).
    """
    forced = []
    for flag in FLAGS:
        try:
            on = bool(getattr(cfg, flag, False))
        except Exception:
            continue
        if not on:
            continue
        for name in GROUPS[flag]:
            try:
                cur = getattr(cfg, name, None)
            except Exception:
                continue
            off = off_value(name, cur)
            if off is None or cur == off:
                continue
            try:
                setattr(cfg, name, off)
            except Exception:
                continue
            forced.append(name)
    return forced
